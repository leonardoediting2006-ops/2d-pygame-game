pub struct Font {
    tex: Texture2D,
    pub canvas: Canvas,
}

pub const GW: f32 = 6.0; // avanzamento orizzontale
pub const GH: f32 = 7.0;

impl Font {
    pub fn new() -> Self {
        let n = GLYPHS.len() as i32;
        let mut c = Canvas::new(n * 6, 7);
        for (i, (_, rows)) in GLYPHS.iter().enumerate() {
            for (y, r) in rows.iter().enumerate() {
                for x in 0..5 {
                    if r & (0x10 >> x) != 0 {
                        c.set(i as i32 * 6 + x, y as i32, [255, 255, 255, 255]);
                    }
                }
            }
        }
        Font { tex: c.tex(), canvas: c }
    }

    fn glyph(ch: char) -> Option<(usize, Option<i32>)> {
        // accenti: lettera base + segno sopra (-1 grave, 1 acuto)
        let (base, acc) = match ch {
            'à' | 'À' => ('A', Some(-1)),
            'è' | 'È' => ('E', Some(-1)),
            'é' | 'É' => ('E', Some(1)),
            'ì' | 'Ì' => ('I', Some(-1)),
            'ò' | 'Ò' => ('O', Some(-1)),
            'ù' | 'Ù' => ('U', Some(-1)),
            '×' => ('x', None),
            c => (c.to_ascii_uppercase(), None),
        };
        GLYPHS.iter().position(|(g, _)| *g == base).map(|i| (i, acc))
    }

    pub fn width(&self, s: &str, scale: f32) -> f32 {
        s.chars().count() as f32 * GW * scale - scale
    }

    pub fn draw(&self, s: &str, x: f32, y: f32, scale: f32, col: Color) {
        let mut cx = x.round();
        let y = y.round();
        for ch in s.chars() {
            if let Some((i, acc)) = Self::glyph(ch) {
                draw_texture_ex(
                    &self.tex,
                    cx,
                    y,
                    col,
                    DrawTextureParams {
                        source: Some(Rect::new(i as f32 * 6.0, 0.0, 5.0, 7.0)),
                        dest_size: Some(vec2(5.0 * scale, 7.0 * scale)),
                        ..Default::default()
                    },
                );
                if let Some(a) = acc {
                    let ax = if a < 0 { cx + 1.0 * scale } else { cx + 2.0 * scale };
                    draw_rectangle(ax, y - 2.0 * scale, scale, scale, col);
                    draw_rectangle(ax + scale, y - 1.0 * scale, scale, scale, col);
                }
            }
            cx += GW * scale;
        }
    }

    /// Testo con ombra (leggibile su qualsiasi sfondo)
    pub fn draw_shadow(&self, s: &str, x: f32, y: f32, scale: f32, col: Color, sh: Color) {
        self.draw(s, x + scale, y + scale, scale, sh);
        self.draw(s, x, y, scale, col);
    }

    pub fn draw_center(&self, s: &str, cx: f32, y: f32, scale: f32, col: Color, sh: Color) {
        let w = self.width(s, scale);
        self.draw_shadow(s, (cx - w / 2.0).round(), y, scale, col, sh);
    }
}
